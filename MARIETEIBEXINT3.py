    "    tech_score = tech['tech_score'] if tech else 0\n",
    "    fund_score = fund['score'] if fund else 0\n",
    "    etiqueta = None\n",
    "    if tech_score>=TECH_THRESHOLD and fund_score>=FUND_THRESHOLD and news>=NEWS_THRESHOLD:\n",
    "        etiqueta=\"STRONG BUY\"\n",
