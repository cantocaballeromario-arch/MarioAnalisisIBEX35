    "PE_MAX = 35.0\n",
    "DTE_MAX = 1.5\n",
    "ROE_MIN = 0.05\n",
    "PM_MIN = 0.03\n",
    "RSI_MAX_FOR_BUY = 50.0\n",
    "\n",
    "# -------------------------\n",
    "# Empresas IBEX 35\n",
