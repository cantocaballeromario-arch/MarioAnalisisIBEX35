    "INTERVAL = st.sidebar.selectbox(\"Intervalo\", [\"1d\",\"1wk\",\"1mo\"], index=0)\n",
    "TECH_THRESHOLD = 2\n",
    "FUND_THRESHOLD = 2\n",
    "NEWS_THRESHOLD = 0.05\n",
    "NEWS_PER_SOURCE = 5\n",
